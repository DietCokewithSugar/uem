// 用户声音情绪与 ETS 维度识别（演示用关键词规则；正式环境由大模型按「模型提示词管理」完成）
const rules = [
  [/限额|额度|流程|步骤|找不到|入口|搜索/, '功能流程'],
  [/客服|扣款|扣费|收费|服务/, '运营服务'],
  [/看不懂|提示|说明|信息|术语/, '信息认知'],
  [/封号|冻结|安全|验证|人脸|U盾|证书/, '安全感知'],
  [/卡|慢|没反应|闪退|报错|加载/, '系统性能'],
  [/弹窗|小窗口|按钮|操作/, '交互设计'],
  [/颜色|图标|字体|夜间/, '视觉设计'],
  [/智能|推荐|AI/, '智能化']
]
export function classifyVoice(text = '') {
  const dim = rules.find(([re]) => re.test(text))?.[1] || '功能流程'
  let emotion = '中性'
  if (/很好|点赞|顺畅|好用|满意|方便/.test(text)) emotion = '正面'
  if (/不|慢|卡|麻烦|讨厌|难|看不懂|失败|延迟/.test(text)) emotion = '轻度负面'
  if (/很麻烦|讨厌|没办法|无法|反复/.test(text)) emotion = '中度负面'
  if (/投诉|封号|严重|误导/.test(text)) emotion = '高度负面'
  return { emotion, dim }
}
