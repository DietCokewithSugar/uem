function makeVoice(i, product, daysBack) {
  const d = new Date(2026, 9, 13, 15, 58)
  d.setMinutes(d.getMinutes() - Math.floor(daysBack * 24 * 60 + rand() * 600))
  const column = pick(product.columns)
  const desc = pick(voiceTemplates[column] || voiceTemplates.default)
  const negative = /投诉|卡|没反应|不|慢|讨厌|麻烦|延迟|过低|看不懂/.test(desc) && !/没有问题|很好|点赞|顺畅/.test(desc)
  return {
    id: `V${100000 + i}`,
    time: `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`,
    source: rand() > 0.15 ? 'app用户反馈' : pick(voiceSources),
    column,
    product: product.name,
    desc,
    emotion: negative ? pick(emotions.slice(2)) : pick(emotions.slice(0, 2)),
    dim: negative ? pick(etsDims.slice(0, 5)) : pick(etsDims),
    valid: rand() > 0.1
  }
}
